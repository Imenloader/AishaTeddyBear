// Seeded random number generator
const mulberry32 = (a: number) => {
  return () => {
    let t = a += 0x6D2B79F5;
    t = Math.imul(t ^ t >>> 15, t | 1);
    t ^= t + Math.imul(t ^ t >>> 7, t | 61);
    return ((t ^ t >>> 14) >>> 0) / 4294967296;
  }
};

export const getDailyMessage = (mode: AppMode, date: Date = new Date()) => {
  const isFriday = date.getDay() === 5;
  const dayOfYear = Math.floor((date.getTime() - new Date(date.getFullYear(), 0, 0).getTime()) / 1000 / 60 / 60 / 24);
  
  // Create a seeded random generator based on the day of the year
  const random = mulberry32(date.getFullYear() * 1000 + dayOfYear);
  
  const getRand = (arr: any[]) => arr[Math.floor(random() * arr.length)];

  if (isFriday) {
    const letterIndex = dayOfYear % FRIDAY_LETTERS.length;
    return {
      type: 'friday_letter',
      title: '💌 رسالة الجمعة من خطيبك',
      content: FRIDAY_LETTERS[letterIndex]
    };
  }

  const endearment = getRand(ENDEARMENTS);
  const promise = getRand(PROMISES);
  const quran = getRand(QURAN_VERSES);
  const duaa = getRand(DUAAS);
  const action = getRand(ACTIONS);

  let content = '';

  switch (mode) {
    case 'heart':
      content = `${endearment}.. ${promise} ${duaa} ${action}`;
      break;
    case 'sparkle':
      content = `${endearment}.. ${action} ${promise} ${duaa}`;
      break;
    case 'dream':
      content = `${endearment}.. ${quran} ${promise}`;
      break;
    case 'soul':
    default:
      content = `${endearment}.. ${quran} ${duaa}`;
      break;
  }

  return {
    type: 'daily_message',
    title: '💬 رسالة النهاردة من حبيبك',
    content
  };
};
